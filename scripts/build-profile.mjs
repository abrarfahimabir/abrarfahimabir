// The diagram lives in its own 424 × 276 box and is placed by each hero layout.
// Two curves form one loop: React sends a request, Django answers with JSON.
const REQ = { p0: [98, 128], c1: [98, 186], c2: [140, 212], p1: [226, 212] };
