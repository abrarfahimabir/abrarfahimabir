const esc = (s) =>
  String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

const slugify = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

// Rough advance widths (in em) for common sans-serif fonts. Used only to size
// chips and to shrink long text, so it errs on the wide side.
const NARROW = new Set([...'iljtfrI.,:;·\' |/()-[]!']);
const WIDE = new Set([...'mwMWDGOQCHNRUBEKPSVXYA&%@']);
function textWidth(str, size, { bold = false, mono = false } = {}) {
  if (mono) return str.length * 0.6 * size;
  let em = 0;
  for (const ch of str) em += NARROW.has(ch) ? 0.27 : WIDE.has(ch) ? 0.72 : 0.56;
  return em * size * (bold ? 1.06 : 1);
}

// Largest font size (up to `size`) that keeps `text` within `maxWidth`,
// with headroom for wider fonts such as DejaVu Sans on Linux.
function fit(text, size, maxWidth, opts) {
  const w = textWidth(text, size, opts) * 1.15;
  return w <= maxWidth ? size : Math.floor((size * maxWidth) / w);
}

