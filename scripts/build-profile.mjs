async function loadConfig() {
  let cfg;
  try {
    cfg = JSON.parse(await readFile(path.join(ROOT, 'profile.config.json'), 'utf8'));
  } catch (err) {
    fail(`profile.config.json could not be read. Check for a missing comma or quote.\n  ${err.message}`);
  }
  for (const key of ['username', 'name', 'role', 'subtitle']) {
    if (typeof cfg[key] !== 'string' || !cfg[key].trim()) fail(`profile.config.json: "${key}" must be a non-empty text value.`);
  }
  if (!cfg.stack || typeof cfg.stack !== 'object' || !Object.keys(cfg.stack).length) {
    fail('profile.config.json: "stack" needs at least one group, for example "Frontend": ["react"].');
  }
  for (const [group, items] of Object.entries(cfg.stack)) {
    if (!Array.isArray(items) || !items.length || !items.every((i) => typeof i === 'string' && i.trim())) {
      fail(`profile.config.json: stack group "${group}" must be a list of names, for example ["react", "django"].`);
    }
  }
  const activity = { exclude: [], recentRepos: 3, ...(cfg.activity || {}) };
  if (!Array.isArray(activity.exclude)) fail('profile.config.json: "activity.exclude" must be a list of repository names.');
  activity.recentRepos = Math.max(1, Math.min(6, Number(activity.recentRepos) || 3));
  return { ...cfg, activity };
}

