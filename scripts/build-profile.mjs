function motionCss() {
  const len = Math.round(curveLength(REQ));
  const dash = 38;
  const start = dash + 6;
  const end = -(len + 6);
  // One 8-second cycle: request travels (0–30%), pause, response returns (46–76%), rest.
  return `
    .pulse { stroke-dasharray: ${dash} ${len + 80}; stroke-dashoffset: ${start}; opacity: 0; }
    .req { animation: req 8s cubic-bezier(.45,.05,.25,1) infinite; }
    .res { animation: res 8s cubic-bezier(.45,.05,.25,1) infinite; }
    @keyframes req {
      0% { stroke-dashoffset: ${start}; opacity: 0; }
      4%, 26% { opacity: 1; }
      30%, 100% { stroke-dashoffset: ${end}; opacity: 0; }
    }
    @keyframes res {
      0%, 46% { stroke-dashoffset: ${start}; opacity: 0; }
      50%, 72% { opacity: 1; }
      76%, 100% { stroke-dashoffset: ${end}; opacity: 0; }
    }
    @media (prefers-reduced-motion: reduce) { .pulse { animation: none; display: none; } }`;
}

