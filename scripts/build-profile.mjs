/* --------------------------------------------------------- stack block */

function buildStack(cfg, icons) {
  const files = [];
  const groups = Object.entries(cfg.stack).map(([group, names]) => {
    const tint = tintFor(group);
    const items = names.map((name) => {
      const tech = techFor(name, icons);
      files.push([`assets/stack/${tech.file}.svg`, chipSvg(tech, tint)]);
      const img = `<img src="assets/stack/${tech.file}.svg" height="32" alt="${esc(tech.label)}">`;
      return tech.url ? `<a href="${tech.url}">${img}</a>` : img;
    });
    return `<p>\n<b>${esc(group)}</b><br>\n${items.join('\n')}\n</p>`;
  });
  return { files, block: groups.join('\n\n') };
}

