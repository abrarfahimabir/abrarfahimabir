// Whole-number percentages that always add up to 100.
function percentages(entries) {
  const total = entries.reduce((s, [, v]) => s + v, 0);
  const raw = entries.map(([name, v]) => ({ name, exact: (v / total) * 100 }));
  raw.forEach((r) => (r.pct = Math.floor(r.exact)));
  let left = 100 - raw.reduce((s, r) => s + r.pct, 0);
  [...raw].sort((a, b) => (b.exact % 1) - (a.exact % 1)).forEach((r) => {
    if (left > 0) {
      r.pct += 1;
      left -= 1;
    }
  });
  return raw.filter((r) => r.pct > 0);
}

