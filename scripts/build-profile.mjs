function replaceBlock(readme, name, content) {
  const starts = readme.split(`<!-- ${name}:START`).length - 1;
  const ends = readme.split(`<!-- ${name}:END -->`).length - 1;
  const re = new RegExp(`(<!-- ${name}:START[^]*?-->)[^]*?(<!-- ${name}:END -->)`);
  if (starts !== 1 || ends !== 1 || !re.test(readme)) {
    fail(`README.md needs exactly one "<!-- ${name}:START ... -->" line and one "<!-- ${name}:END -->" line, in that order. SETUP.md shows how to restore them.`);
  }
  return readme.replace(re, (_, open, close) => `${open}\n${content}\n${close}`);
}

async function writeIfChanged(rel, content) {
  const file = path.join(ROOT, rel);
  let old = null;
  try {
    old = await readFile(file, 'utf8');
  } catch {
    /* new file */
  }
  if (old === content) return false;
  await mkdir(path.dirname(file), { recursive: true });
  const tmp = `${file}.tmp-${process.pid}`;
  await writeFile(tmp, content);
  await rename(tmp, file);
  return true;
}

